#!/usr/bin/env python3
"""
参考PDFから構造・スタイル情報を抽出する（ガイド生成）
標準ライブラリのみを使用

使用例: python3 edu-creator/script/extract_pdf_structure.py material/sample/Python基礎知識ガイド.pdf
"""

import os


# PDF処理が必要な場合は、内容を視覚的に確認するための「ガイド」を生成
def generate_style_guide():
    """PDF見た目に基づいた Markdown スタイルガイドを生成"""
    guide = '''# 📐 PDF出力スタイルガイド（参考PDF準拠）

## 制約事項
これらはサンプルPDFの見た目に基づいています。

### テーブル制約
- **最大幅**: 100文字相当（A4 1ページ内に収まる）
- **列数**: 3-4列推奨
- **例**: コンポーネント名 | 役割 | 使用例

### コード行制約
- **最大長**: 70文字
- **超過時の対処**:
  - 改行を挿入する
  - コメント追加で補足：「// 他の設定は省略」

### セクション区切り
- `# ` で主要セクション開始
- `## ` で小セクション開始
- セクション間は空行1行で区切る
- **改ページを明示する場合**: `<!-- pagebreak -->` を挿入

### 見出し構造
```
# 最大見出し（チャプタータイトル）
## セクション（主要トピック）
### 小セクション（サブトピック）
#### 細部（補足）
```

### リスト形式
- 箇条書き: `-` または `*` で統一
- 番号付き: `1.` `2.` で統一
- ネスト: 2段階まで推奨

### テーブル例（良い例）
```markdown
| 技術名 | キッチン類似例 | 役割 |
|-------|-------------|------|
| Node.js | コンロ 🔥 | プログラムを「調理」 |
| Docker | キッチン一式 🎒 | 道具を箱に詰めて運ぶ |
```

### コード例（良い例）
```javascript
// 行数: 最大25行
// 行長: 最大70文字
const config = {
  name: "app",
  version: "1.0.0"
};
```

## 自己完結性（必須）
- **「ファイルを開いてください」禁止** → コンテンツをインライン化
- **「詳細は〇〇参照」禁止** → 必要な情報は全て含める
- **コード説明** → 各コードブロック後に行ごと説明
- **コマンド説明** → 実行例と期待値を両方記載

## 期待値表示の例
```
$ node -v
v25.6.1

「このように v25.x.x が表示されたら成功です」
```

## よくある問題と対処
- テーブルが右端で切れる → 列を削減、またはテーブル横スクロール不可なので列幅を短くする
- コード行が折り返される → 70文字以内に収める or 複数ブロックに分割
- 見出しレベルが混乱 → # → ## → ### の順序を守る
'''
    return guide


def main():
    print("=" * 60)
    print("📐 PDF スタイルガイド生成")
    print("=" * 60)
    print()

    guide = generate_style_guide()
    print(guide)

    # ファイルに保存
    output_path = "edu-creator/prompt/task/STYLE_GUIDE.md"
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(guide)

    print()
    print(f"✅ スタイルガイド保存: {output_path}")


if __name__ == "__main__":
    main()
